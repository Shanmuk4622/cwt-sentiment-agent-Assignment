"""
Automated Institutional Reporting Engine:
Generates:
1. reports/sentiment_outlook_1page.md: 1-Page Executive Sentiment Outlook Summary
2. reports/evaluation_report.md: Full Quantitative Data Science Evaluation Report
   (Sharpe Ratio, Sortino Ratio, Max Drawdown, Out-of-Sample Tables, Methodology)
"""

from datetime import datetime, timezone
import json
import logging
